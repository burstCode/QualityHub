-- Схема БД системы динамического анализа результатов многоуровневого тестирования
-- СУБД: PostgreSQL. Сгенерировано из спецификаций сущностей (ЛР1, п. 2.4).

CREATE TABLE PROJECT (
    PROJECT_ID                     SERIAL,
    PROJECT_NAME                   VARCHAR(100) NOT NULL,
    PROJECT_DESCRIPTION            VARCHAR(500),
    PROJECT_REPOSITORY_URL         VARCHAR(255),
    PROJECT_CREATED_AT             TIMESTAMPTZ NOT NULL DEFAULT now(),
    PROJECT_IS_ACTIVE              BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_PROJECT PRIMARY KEY (PROJECT_ID),
    CONSTRAINT UQ_PROJECT_1 UNIQUE (PROJECT_NAME)
);

CREATE TABLE TEST_LEVEL (
    TEST_LEVEL_ID                  SERIAL,
    TEST_LEVEL_CODE                VARCHAR(30) NOT NULL,
    TEST_LEVEL_NAME                VARCHAR(100) NOT NULL,
    TEST_LEVEL_ORDER               SMALLINT NOT NULL,
    CONSTRAINT PK_TEST_LEVEL PRIMARY KEY (TEST_LEVEL_ID),
    CONSTRAINT UQ_TEST_LEVEL_1 UNIQUE (TEST_LEVEL_CODE)
);

CREATE TABLE TEST_RUN (
    TEST_RUN_ID                    BIGSERIAL,
    PROJECT_ID                     INTEGER NOT NULL,
    TEST_LEVEL_ID                  INTEGER NOT NULL,
    TEST_RUN_BUILD_NUMBER          VARCHAR(50) NOT NULL,
    TEST_RUN_BRANCH                VARCHAR(100),
    TEST_RUN_COMMIT_HASH           VARCHAR(64),
    TEST_RUN_ENVIRONMENT           VARCHAR(50),
    TEST_RUN_STARTED_AT            TIMESTAMPTZ NOT NULL,
    TEST_RUN_FINISHED_AT           TIMESTAMPTZ NOT NULL,
    TEST_RUN_DURATION_MS           BIGINT NOT NULL,
    TEST_RUN_MAX_VUS               INTEGER,
    TEST_RUN_INFRA_WARNING         TEXT,
    TEST_RUN_SOURCE_FORMAT         VARCHAR(30) NOT NULL,
    TEST_RUN_IMPORT_STATUS         SMALLINT NOT NULL,
    TEST_RUN_IMPORT_ERROR          TEXT,
    TEST_RUN_IMPORTED_AT           TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT PK_TEST_RUN PRIMARY KEY (TEST_RUN_ID),
    CONSTRAINT UQ_TEST_RUN_1 UNIQUE (PROJECT_ID, TEST_LEVEL_ID, TEST_RUN_BUILD_NUMBER)
);

CREATE TABLE TEST_CASE (
    TEST_CASE_ID                   BIGSERIAL,
    PROJECT_ID                     INTEGER NOT NULL,
    TEST_LEVEL_ID                  INTEGER NOT NULL,
    TEST_CASE_SUITE                VARCHAR(255) NOT NULL,
    TEST_CASE_NAME                 VARCHAR(500) NOT NULL,
    CONSTRAINT PK_TEST_CASE PRIMARY KEY (TEST_CASE_ID),
    CONSTRAINT UQ_TEST_CASE_1 UNIQUE (PROJECT_ID, TEST_LEVEL_ID, TEST_CASE_NAME)
);

CREATE TABLE TEST_RESULT (
    TEST_RESULT_ID                 BIGSERIAL,
    TEST_RUN_ID                    BIGINT NOT NULL,
    TEST_CASE_ID                   BIGINT NOT NULL,
    TEST_RESULT_STATUS             SMALLINT NOT NULL,
    TEST_RESULT_DURATION_MS        INTEGER NOT NULL,
    TEST_RESULT_ERROR_MESSAGE      TEXT,
    TEST_RESULT_STACK_TRACE        TEXT,
    TEST_RESULT_REQUEST_COUNT      INTEGER,
    TEST_RESULT_P95_MS             INTEGER,
    TEST_RESULT_ERROR_RATE         NUMERIC(5,4),
    CONSTRAINT PK_TEST_RESULT PRIMARY KEY (TEST_RESULT_ID),
    CONSTRAINT UQ_TEST_RESULT_1 UNIQUE (TEST_RUN_ID, TEST_CASE_ID)
);

CREATE TABLE METRIC_DEFINITION (
    METRIC_ID                      SERIAL,
    METRIC_CODE                    VARCHAR(50) NOT NULL,
    METRIC_SOURCE                  SMALLINT NOT NULL,
    METRIC_NAME                    VARCHAR(150) NOT NULL,
    METRIC_UNIT                    VARCHAR(20) NOT NULL,
    METRIC_SPRINT_AGGREGATE        SMALLINT NOT NULL,
    METRIC_DESCRIPTION             VARCHAR(500),
    METRIC_HIGHER_IS_BETTER        BOOLEAN NOT NULL,
    CONSTRAINT PK_METRIC_DEFINITION PRIMARY KEY (METRIC_ID),
    CONSTRAINT UQ_METRIC_DEFINITION_1 UNIQUE (METRIC_CODE)
);

CREATE TABLE METRIC_VALUE (
    METRIC_VALUE_ID                BIGSERIAL,
    TEST_RUN_ID                    BIGINT NOT NULL,
    METRIC_ID                      INTEGER NOT NULL,
    METRIC_VALUE_VALUE             NUMERIC(18,4) NOT NULL,
    METRIC_VALUE_CALCULATED_AT     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT PK_METRIC_VALUE PRIMARY KEY (METRIC_VALUE_ID),
    CONSTRAINT UQ_METRIC_VALUE_1 UNIQUE (TEST_RUN_ID, METRIC_ID)
);

CREATE TABLE THRESHOLD_RULE (
    THRESHOLD_RULE_ID              SERIAL,
    PROJECT_ID                     INTEGER NOT NULL,
    METRIC_ID                      INTEGER NOT NULL,
    TEST_LEVEL_ID                  INTEGER,
    THRESHOLD_RULE_OPERATOR        VARCHAR(5) NOT NULL,
    THRESHOLD_RULE_VALUE           NUMERIC(18,4) NOT NULL,
    THRESHOLD_RULE_SEVERITY        SMALLINT NOT NULL,
    THRESHOLD_RULE_IS_ACTIVE       BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_THRESHOLD_RULE PRIMARY KEY (THRESHOLD_RULE_ID),
    CONSTRAINT CK_THRESHOLD_RULE_OPERATOR CHECK (THRESHOLD_RULE_OPERATOR IN ('<', '<=', '>', '>='))
);

CREATE TABLE NOTIFICATION (
    NOTIFICATION_ID                BIGSERIAL,
    THRESHOLD_RULE_ID              INTEGER NOT NULL,
    METRIC_VALUE_ID                BIGINT NOT NULL,
    APP_USER_ID                    INTEGER NOT NULL,
    NOTIFICATION_CHANNEL           SMALLINT NOT NULL,
    NOTIFICATION_TEXT              TEXT NOT NULL,
    NOTIFICATION_STATUS            SMALLINT NOT NULL,
    NOTIFICATION_CREATED_AT        TIMESTAMPTZ NOT NULL DEFAULT now(),
    NOTIFICATION_SENT_AT           TIMESTAMPTZ,
    CONSTRAINT PK_NOTIFICATION PRIMARY KEY (NOTIFICATION_ID)
);

CREATE TABLE APP_USER (
    APP_USER_ID                    SERIAL,
    USER_ROLE_ID                   INTEGER NOT NULL,
    APP_USER_LOGIN                 VARCHAR(50) NOT NULL,
    APP_USER_PASSWORD_HASH         VARCHAR(255) NOT NULL,
    APP_USER_FULL_NAME             VARCHAR(150) NOT NULL,
    APP_USER_EMAIL                 VARCHAR(150) NOT NULL,
    APP_USER_IS_ACTIVE             BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_APP_USER PRIMARY KEY (APP_USER_ID),
    CONSTRAINT UQ_APP_USER_1 UNIQUE (APP_USER_LOGIN)
);

CREATE TABLE USER_ROLE (
    USER_ROLE_ID                   SERIAL,
    USER_ROLE_NAME                 VARCHAR(50) NOT NULL,
    CONSTRAINT PK_USER_ROLE PRIMARY KEY (USER_ROLE_ID),
    CONSTRAINT UQ_USER_ROLE_1 UNIQUE (USER_ROLE_NAME)
);

CREATE TABLE PROJECT_ACCESS (
    APP_USER_ID                    INTEGER NOT NULL,
    PROJECT_ID                     INTEGER NOT NULL,
    CONSTRAINT PK_PROJECT_ACCESS PRIMARY KEY (APP_USER_ID, PROJECT_ID)
);

CREATE TABLE SUBSCRIPTION (
    APP_USER_ID                    INTEGER NOT NULL,
    PROJECT_ID                     INTEGER NOT NULL,
    NOTIFICATION_CHANNEL           SMALLINT NOT NULL,
    MIN_SEVERITY                   SMALLINT NOT NULL,
    CONSTRAINT PK_SUBSCRIPTION PRIMARY KEY (APP_USER_ID, PROJECT_ID, NOTIFICATION_CHANNEL)
);

CREATE TABLE API_TOKEN (
    API_TOKEN_ID                   SERIAL,
    PROJECT_ID                     INTEGER NOT NULL,
    API_TOKEN_NAME                 VARCHAR(100) NOT NULL,
    API_TOKEN_HASH                 VARCHAR(255) NOT NULL,
    API_TOKEN_EXPIRES_AT           TIMESTAMPTZ NOT NULL,
    API_TOKEN_IS_ACTIVE            BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_API_TOKEN PRIMARY KEY (API_TOKEN_ID)
);

CREATE TABLE REPORT (
    REPORT_ID                      SERIAL,
    PROJECT_ID                     INTEGER NOT NULL,
    APP_USER_ID                    INTEGER NOT NULL,
    REPORT_PERIOD_FROM             DATE NOT NULL,
    REPORT_PERIOD_TO               DATE NOT NULL,
    REPORT_FORMAT                  VARCHAR(10) NOT NULL,
    REPORT_PARAMETERS              JSONB,
    REPORT_CREATED_AT              TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT PK_REPORT PRIMARY KEY (REPORT_ID)
);

CREATE TABLE MONITORING_SOURCE (
    MONITORING_SOURCE_ID           SERIAL,
    PROJECT_ID                     INTEGER NOT NULL,
    MONITORING_SOURCE_NAME         VARCHAR(100) NOT NULL,
    MONITORING_SOURCE_API_URL      VARCHAR(255) NOT NULL,
    MONITORING_SOURCE_AUTH_TOKEN   VARCHAR(255) NOT NULL,
    MONITORING_SOURCE_IS_ACTIVE    BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_MONITORING_SOURCE PRIMARY KEY (MONITORING_SOURCE_ID)
);

CREATE TABLE MONITORED_ITEM (
    MONITORED_ITEM_ID              SERIAL,
    MONITORING_SOURCE_ID           INTEGER NOT NULL,
    TEST_LEVEL_ID                  INTEGER NOT NULL,
    METRIC_ID                      INTEGER,
    MONITORED_ITEM_EXTERNAL_ID     VARCHAR(50) NOT NULL,
    MONITORED_ITEM_NAME            VARCHAR(150) NOT NULL,
    MONITORED_ITEM_HOST            VARCHAR(150),
    MONITORED_ITEM_UNIT            VARCHAR(20) NOT NULL,
    MONITORED_ITEM_AGGREGATE       SMALLINT NOT NULL,
    CONSTRAINT PK_MONITORED_ITEM PRIMARY KEY (MONITORED_ITEM_ID)
);

CREATE TABLE INFRA_SAMPLE (
    INFRA_SAMPLE_ID                BIGSERIAL,
    TEST_RUN_ID                    BIGINT NOT NULL,
    MONITORED_ITEM_ID              INTEGER NOT NULL,
    INFRA_SAMPLE_TIME              TIMESTAMPTZ NOT NULL,
    INFRA_SAMPLE_VALUE             NUMERIC(18,4) NOT NULL,
    CONSTRAINT PK_INFRA_SAMPLE PRIMARY KEY (INFRA_SAMPLE_ID)
);

CREATE TABLE SPRINT (
    SPRINT_ID                      SERIAL,
    PROJECT_ID                     INTEGER NOT NULL,
    SPRINT_NAME                    VARCHAR(100) NOT NULL,
    SPRINT_START_DATE              DATE NOT NULL,
    SPRINT_END_DATE                DATE NOT NULL,
    CONSTRAINT PK_SPRINT PRIMARY KEY (SPRINT_ID)
);

